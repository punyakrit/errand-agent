import type { Facts } from "./facts.ts";
import type { ScenarioResult } from "./runner.ts";
import type { SweepResult } from "./sweep.ts";

function show(facts: Facts): string {
  return Object.entries(facts).map(([key, value]) => `${key}=${JSON.stringify(value)}`).join(", ").replaceAll("|", "\\|");
}

export function evalTable(results: ScenarioResult[], sweep: SweepResult, command: string): string {
  const passed = results.filter((result) => result.pass).length;
  const lines = [
    "# Eval table",
    "",
    `Generated by \`${command}\`. Do not edit by hand. "actual" is computed from \`mock_calls\` and the trace.`,
    "",
    `**${passed} of ${results.length} scenarios passed.** Each one also checks all 7 invariants.`,
    "",
    "| Scenario | Mode | Expected | Actual | Result | Notes |",
    "|---|---|---|---|---|---|",
    ...results.map((result) => {
      const name = `${result.id}. ${result.name}`.replaceAll("|", "\\|");
      const notes = result.notes.replaceAll("|", "\\|");
      return `| ${name} | ${result.mode} | ${show(result.expected)} | ${show(result.actual)} | ${result.pass ? "pass" : "**FAIL**"} | ${notes} |`;
    }),
    "",
    "## Seed sweep",
    "",
    `${sweep.seeds} full bookings at the default odds, asserting the invariants only: **${sweep.passed} passed, ${sweep.failed} failed.**`,
    "",
    `Outcomes across the sweep: ${show(sweep.outcomes)}.`,
    "",
    ...sweep.failures.slice(0, 10).map((failure) => `- seed ${failure.seed}: ${failure.problem}`),
  ];
  return `${lines.join("\n")}\n`;
}
